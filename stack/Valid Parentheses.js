/**
 * Type: String / Stack / Easy
 * [20] Valid Parentheses
 *
 * 📌 Условие: Дана строка, содержащая только скобки '(', ')', '{', '}', '[', ']'.
 *             Определите, правильно ли они закрыты.
 *
 * 🔍 Маркеры: скобки, валидность, стек, правильная последовательность.
 * 📏 Тип: Стек (Stack).
 * 🧠 Идея: Используем стек. Открывающие скобки пушим в стек.
 *          При закрывающей - проверяем, что она соответствует последней открытой.
 *
 * ⏱ Сложность: O(n) по времени, O(n) по памяти.
 *
 * @param {string} s - строка со скобками
 * @return {boolean} - true, если скобки расставлены правильно
 */
var isValid = function(s) {
    const stack = [];
    const map = {
        ')': '(',
        '}': '{',
        ']': '['
    };

    for (const char of s) {
        if (char === '(' || char === '{' || char === '[') {
            stack.push(char);
        } else {
            if (stack.length === 0 || stack.pop() !== map[char]) {
                return false;
            }
        }
    }
    return stack.length === 0;
};