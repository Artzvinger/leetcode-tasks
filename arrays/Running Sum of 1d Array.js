/**
 * Type: Array / Easy
 * [1480] Running Sum of 1d Array
 *
 * 📌 Условие: Дан массив nums. Верните массив, где каждый элемент
 *             равен сумме всех предыдущих элементов включая текущий.
 *
 * 🔍 Маркеры: префиксная сумма, бегущая сумма.
 * 📏 Тип: Префиксные суммы.
 * 🧠 Идея: Проходим по массиву, накапливая сумму.
 *
 * ⏱ Сложность: O(n) по времени, O(1) по памяти (если изменять на месте).
 *
 * @param {number[]} nums - массив целых чисел
 * @return {number[]} - массив префиксных сумм
 */
var runningSum = function(nums) {
    for (let i = 1; i < nums.length; i++) {
        nums[i] += nums[i - 1];
    }
    return nums;
};