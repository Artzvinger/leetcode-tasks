/**
 * Type: Array / Math / Easy
 * [66] Plus One
 *
 * 📌 Условие: Дан массив цифр, представляющих целое число. Добавьте 1 к числу.
 *
 * 🔍 Маркеры: плюс один, массив цифр, перенос.
 * 📏 Тип: Математика.
 * 🧠 Идея: Идем с конца, добавляем 1. Если цифра становится 10, ставим 0
 *          и переносим 1 дальше. Если все цифры стали 0, добавляем 1 в начало.
 *
 * ⏱ Сложность: O(n) по времени, O(1) по памяти.
 *
 * @param {number[]} digits - массив цифр
 * @return {number[]} - массив после добавления 1
 */
var plusOne = function(digits) {
    for (let i = digits.length - 1; i >= 0; i--) {
        if (digits[i] < 9) {
            digits[i]++;
            return digits;
        }
        digits[i] = 0;
    }
    return [1, ...digits];
};