/**
 * Type: Hash Table / Math / String / Medium
 * [12] Integer to Roman
 *
 * 📌 Условие: Дано целое число в диапазоне от 1 до 3999.
 *             Преобразуйте его в римскую цифру.
 *
 * 🔍 Маркеры: конвертация, число в римскую цифру, диапазон 1-3999.
 * 📏 Тип: Жадный алгоритм (Greedy).
 * 🧠 Идея: Используем упорядоченный список из 13 пар "значение → символ"
 *          от большего к меньшему. Жадно вычитаем максимально возможное
 *          значение, добавляя соответствующий символ к результату.
 *
 * ⏱ Сложность: O(1) по времени (константное число итераций, ≤ 15) и O(1) по памяти.
 *
 * @param {number} num - целое число (1 ≤ num ≤ 3999)
 * @return {string} - римское представление числа
 */
var intToRoman = function(num) {
    const values = [1000, 900, 500, 400, 100, 90, 50, 40, 10, 9, 5, 4, 1];
    const symbols = ["M", "CM", "D", "CD", "C", "XC", "L", "XL", "X", "IX", "V", "IV", "I"];

    let result = "";

    for (let i = 0; i < values.length; i++) {
        while (num >= values[i]) {
            result += symbols[i];
            num -= values[i];
        }
    }

    return result;
};