/**
 * Type: Array / Two Pointers / Easy
 * [26] Remove Duplicates from Sorted Array
 *
 * 📌 Условие: Дан отсортированный массив. Удалите дубликаты так, чтобы каждый
 *             элемент встречался только один раз. Верните новую длину массива.
 *
 * 🔍 Маркеры: отсортированный массив, удалить дубликаты, на месте.
 * 📏 Тип: Два указателя.
 * 🧠 Идея: Используем указатель i для места вставки уникальных элементов.
 *          Проходим по массиву, если текущий элемент != предыдущему уникальному,
 *          копируем его в позицию i.
 *
 * ⏱ Сложность: O(n) по времени, O(1) по памяти.
 *
 * @param {number[]} nums - отсортированный массив
 * @return {number} - новая длина массива
 */
var removeDuplicates = function(nums) {
    if (nums.length === 0) return 0;

    let i = 1;
    for (let j = 1; j < nums.length; j++) {
        if (nums[j] !== nums[j - 1]) {
            nums[i] = nums[j];
            i++;
        }
    }
    return i;
};