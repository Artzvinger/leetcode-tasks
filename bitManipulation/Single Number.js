/**
 * Type: Array / Hash Table / Easy
 * [136] Single Number
 *
 * 📌 Условие: Дан массив целых чисел, где каждый элемент встречается дважды,
 *             кроме одного элемента, который встречается один раз. Найдите его.
 *
 * 🔍 Маркеры: один уникальный элемент, все остальные повторяются дважды.
 * 📏 Тип: Хеш-таблица (Set).
 * 🧠 Идея: Используем Set для отслеживания уникальных элементов.
 *          Если элемент уже есть в Set - удаляем его (значит встретился второй раз).
 *          Если элемента нет - добавляем.
 *          В конце в Set остается только уникальный элемент.
 *
 * ⏱ Сложность: O(n) по времени, O(n) по памяти.
 *
 * @param {number[]} nums - массив целых чисел
 * @return {number} - уникальный элемент
 */
var singleNumber = function(nums) {
    let set = new Set();
    for (const num of nums) {
        if (set.has(num)) {
            set.delete(num);
        } else {
            set.add(num);
        }
    }
    return set.values().next().value; // или [...set][0]
};
