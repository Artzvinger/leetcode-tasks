/**
 * Type: Bit Manipulation / Easy
 * [190] Reverse Bits
 *
 * 📌 Условие: Дано 32-битное беззнаковое целое число n.
 *             Верните число, полученное перестановкой всех битов в обратном порядке.
 *
 * 🔍 Маркеры: reverse bits, 32-битное, перевернуть биты, беззнаковое.
 * 📏 Тип: Битовые операции.
 * 🧠 Идея: Преобразуем число в 32-битную двоичную строку, переворачиваем её
 *          и преобразуем обратно в число через parseInt(..., 2).
 *
 * ⏱ Сложность: O(1) по времени (всегда 32 бита), O(1) по памяти.
 *
 * @param {number} n - 32-битное беззнаковое целое число
 * @return {number} - число с перевернутыми битами
 */

function reverseBits(n){
    let binary = n.toString(2).padStart(32, "0");
    let reversed = binary.split("").reverse().join("");
    return parseInt(reversed, 2);
}
reverseBits(1)