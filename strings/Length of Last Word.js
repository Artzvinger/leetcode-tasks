/**
 * Type: String / Easy
 * [58] Length of Last Word
 *
 * 📌 Условие: Дана строка s, состоящая из слов и пробелов.
 *             Верните длину последнего слова в строке.
 *
 * 🔍 Маркеры: последнее слово, длина, пробелы.
 * 📏 Тип: Строковые операции.
 * 🧠 Идея: Идем с конца строки, пропускаем пробелы, считаем символы слова.
 *
 * ⏱ Сложность: O(n) по времени, O(1) по памяти.
 *
 * @param {string} s - входная строка
 * @return {number} - длина последнего слова
 */
var lengthOfLastWord = function(s) {
    let length = 0;
    let i = s.length - 1;

    while (i >= 0 && s[i] === ' ') i--;
    while (i >= 0 && s[i] !== ' ') {
        length++;
        i--;
    }
    return length;
};